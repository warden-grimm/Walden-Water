import { connect, sleep, browserSend } from './cdp.mjs';
const p = await connect();
await p.send('Runtime.enable');
await p.send('Emulation.clearDeviceMetricsOverride');
await p.ev(`window.__log=[]; (function L(){ const s=__WALDEN_DEBUG__.snapshot(); __log.push([Math.round(performance.now()), s.frames, +s.elapsed.toFixed(4), document.hidden]); requestAnimationFrame(L); })(); document.addEventListener('visibilitychange',()=>__log.push(['vis',Math.round(performance.now()),document.hidden, __WALDEN_DEBUG__.snapshot().running, __WALDEN_DEBUG__.snapshot().frames])); true`);
await sleep(800);
const { windowId } = await browserSend('Browser.getWindowForTarget', { targetId: p.target.id });
await browserSend('Browser.setWindowBounds', { windowId, bounds: { windowState: 'minimized' } });
await sleep(3000);
console.log('minimized', await p.ev(`({hidden:document.hidden, running:__WALDEN_DEBUG__.snapshot().running, frames:__WALDEN_DEBUG__.snapshot().frames})`));
await browserSend('Browser.setWindowBounds', { windowId, bounds: { windowState: 'normal' } });
await sleep(1500);
const log = await p.ev('__log');
const vis = log.filter(x => x[0] === 'vis');
console.log('vis events', JSON.stringify(vis));
const ri = log.findIndex(x => x[0] === 'vis' && x[2] === false);
const hi = log.findIndex(x => x[0] === 'vis' && x[2] === true);
console.log('before hide', JSON.stringify(log.slice(Math.max(0, hi - 2), hi)));
console.log('after resume', JSON.stringify(log.slice(ri, ri + 5)));
p.close();
